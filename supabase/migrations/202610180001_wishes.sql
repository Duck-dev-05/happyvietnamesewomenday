begin;
create table if not exists public.thuong_recipients (
  id bigint generated by default as identity primary key,
  slug text not null unique check (slug ~ '^[a-z0-9-]{1,100}$'),
  name text not null check (length(trim(name)) between 1 and 100),
  handle text not null default '', photo text not null default '', emoji text not null default '💌',
  traits jsonb not null default '[]'::jsonb,
  created_at timestamptz not null default now()
);
create table if not exists public.thuong_wishes (
  id bigint generated by default as identity primary key,
  recipient_id bigint not null references public.thuong_recipients(id),
  body text not null check (length(trim(body)) between 1 and 1500),
  closing text not null default '' check (length(closing) <= 500),
  created_at timestamptz not null default now()
);
create index if not exists thuong_wishes_recipient on public.thuong_wishes(recipient_id,id desc);
alter table public.thuong_recipients enable row level security;
alter table public.thuong_wishes enable row level security;
revoke all on public.thuong_recipients, public.thuong_wishes from anon, authenticated;
grant all on public.thuong_recipients, public.thuong_wishes to service_role;
grant usage, select on sequence public.thuong_recipients_id_seq, public.thuong_wishes_id_seq to service_role;

create or replace function public.thuong_wish_json(r public.thuong_recipients, w public.thuong_wishes)
returns jsonb language sql stable security invoker set search_path = '' as $$
  select jsonb_build_object('id',r.id,'slug',r.slug,'name',r.name,'handle',r.handle,'photo',r.photo,
    'emoji',r.emoji,'traits',r.traits,'wish',coalesce(w.body,''),'appreciation',coalesce(w.closing,''),
    'wishId',w.id,'createdAt',w.created_at);
$$;

create or replace function public.thuong_sync_profiles(profiles jsonb)
returns void language plpgsql security invoker set search_path = '' as $$
declare p jsonb;
begin
  for p in select value from jsonb_array_elements(profiles) loop
    insert into public.thuong_recipients(slug,name,handle,photo,emoji,traits)
    values(p->>'slug',p->>'name',p->>'handle',p->>'photo',p->>'emoji',coalesce(p->'traits','[]'::jsonb))
    on conflict(slug) do update set name=excluded.name,handle=excluded.handle,photo=excluded.photo,emoji=excluded.emoji,traits=excluded.traits;
  end loop;
end;
$$;

create or replace function public.thuong_list_recipients()
returns jsonb language sql stable security invoker set search_path = '' as $$
  select coalesce(jsonb_agg(public.thuong_wish_json(r,w) order by r.id),'[]'::jsonb)
  from public.thuong_recipients r left join public.thuong_wishes w on w.id =
    (select id from public.thuong_wishes where recipient_id=r.id order by id desc limit 1);
$$;
create or replace function public.thuong_all_wishes()
returns jsonb language sql stable security invoker set search_path = '' as $$
  select coalesce(jsonb_agg(public.thuong_wish_json(r,w) order by w.id desc),'[]'::jsonb)
  from public.thuong_wishes w join public.thuong_recipients r on r.id=w.recipient_id;
$$;

create or replace function public.thuong_save_wish(p_slug text,p_name text,p_wish text,p_closing text)
returns jsonb language plpgsql security invoker set search_path = '' as $$
declare r public.thuong_recipients; w public.thuong_wishes; is_new boolean := false;
begin
  insert into public.thuong_recipients(slug,name) values(p_slug,trim(p_name)) on conflict(slug) do nothing;
  -- Serialize submissions for one recipient so identical retries cannot race.
  select * into strict r from public.thuong_recipients where slug=p_slug for update;
  if r.name <> trim(p_name) then raise exception 'Recipient name conflict' using errcode='P0001'; end if;
  select * into w from public.thuong_wishes where recipient_id=r.id and body=trim(p_wish) and closing=trim(p_closing) order by id limit 1;
  if not found then
    insert into public.thuong_wishes(recipient_id,body,closing) values(r.id,trim(p_wish),trim(p_closing)) returning * into w;
    is_new := true;
  end if;
  return jsonb_build_object('recipient',public.thuong_wish_json(r,w),'created',is_new);
end;
$$;

revoke all on function public.thuong_wish_json(public.thuong_recipients,public.thuong_wishes) from public, anon, authenticated;
revoke all on function public.thuong_sync_profiles(jsonb) from public, anon, authenticated;
revoke all on function public.thuong_list_recipients() from public, anon, authenticated;
revoke all on function public.thuong_all_wishes() from public, anon, authenticated;
revoke all on function public.thuong_save_wish(text,text,text,text) from public, anon, authenticated;
grant execute on function public.thuong_wish_json(public.thuong_recipients,public.thuong_wishes) to service_role;
grant execute on function public.thuong_sync_profiles(jsonb) to service_role;
grant execute on function public.thuong_list_recipients() to service_role;
grant execute on function public.thuong_all_wishes() to service_role;
grant execute on function public.thuong_save_wish(text,text,text,text) to service_role;
notify pgrst, 'reload schema';
commit;
